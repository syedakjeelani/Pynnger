GOOD = (
    '"""Util."""\n\n\ndef add(a: int, b: int) -> int:\n    """Add two numbers."""\n    return a + b\n'
    + "\n".join(
        f'\n\ndef f{i}(x: int) -> int:\n    """Function {i}."""\n    return x + {i}\n'
        for i in range(6)
    )
)


def record(source: str = GOOD, license: str = "MIT", path: str = "pkg/util.py") -> SourceRecord:
    return SourceRecord(path=path, source=source, license=license)


@pytest.mark.parametrize(
    ("rec", "reason"),
    [
        (record(license="GPL-3.0"), "license"),
        (record(source="x = 1\n"), "size"),
        (record(source="# Auto-generated by protoc. DO NOT EDIT\n" + GOOD), "generated"),
        (record(source=GOOD + "\nX = '" + "a" * 1200 + "'\n"), "long_line"),
        (record(source=GOOD + "\ndef broken(:\n"), "syntax"),
        (record(source=GOOD + "\nAPI_KEY = 'sk-live-abcdef123456'\n"), "secret"),
        (
            record(
                source="\n".join(
                    f"def compute_value_{i}(first, second):\n    return first + second + {i}\n"
                    for i in range(12)
                )
            ),
            "quality",
        ),
    ],
)
def test_filter_reasons(rec: SourceRecord, reason: str) -> None:
    decision = evaluate(rec, min_quality=0.9)
    assert not decision.keep and decision.reason == reason


def test_filter_keeps_good_code_and_counts_reasons() -> None:
    kept, reasons = filter_records(
        [record(), record(license="GPL-3.0"), record(license="apache-2.0")]
    )
    assert len(kept) == 2 and reasons == {"ok": 2, "license": 1}


def test_dedup_removes_near_duplicates_but_keeps_distinct_text() -> None:
    a = "\n".join(f"def func_{i}(x):\n    return x * {i} + helper_{i}(x)" for i in range(40))
    near = a.replace("def func_3(x)", "def renamed_3(x)")  # one function renamed: ~97% similar
    other = "\n".join(
        f"class Thing{i}:\n    value = {i * 7}\n    name = 'item {i}'" for i in range(40)
    )
    assert dedup([a, near, other, a]) == [0, 2]


def test_decontaminate_flags_overlap_with_banned_text() -> None:
    banned = [
        "write a function that turns arbitrary text into a url friendly slug with an optional maximum length"
    ]
    clean = decontaminate(
        [
            "Please write a function that turns arbitrary text into a url friendly slug with an optional maximum length now",
            "Build a rate limiter using a token bucket and an injected clock for tests",
        ],
        banned,
    )
    assert clean == [False, True]


def test_seed_tasks_are_deterministic_and_unique() -> None:
    a, b = seed_tasks(50), seed_tasks(50)
    assert a == b and len(set(a)) == 50 and all("pytest" in t for t in a)


