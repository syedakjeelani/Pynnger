def test_sft_prompts_match_the_prompts_used_at_inference() -> None:
    backend = demo_backend()
    made = generate_verified(DEMO_TASK, backend, Settings(backend="mock"))
    assert made is not None
    rows = sft_rows(made)
    row_prompts = {r["prompt"][1]["content"] for r in rows}
    seen_in_inference = {c["prompt"] for c in backend.calls if c["stage"] in {"plan", "code"}}
    assert (
        seen_in_inference <= row_prompts
    )  # the exact text the model will see is what it trained on
    assert len(rows) == 1 + 5 + 1


def test_sft_targets_are_final_files_and_parse_as_plans(example: VerifiedExample) -> None:
    rows = sft_rows(example)
