    out = tmp_path / "v.jsonl"
    settings = Settings(backend="mock")
    first = generate_dataset([DEMO_TASK], demo_backend(), settings, out)
    second = generate_dataset([DEMO_TASK, DEMO_TASK + " again"], demo_backend(), settings, out)
